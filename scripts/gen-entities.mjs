// Generates packages/core/src/entities.generated.ts: the HTML named character reference table
// used by the WebVTT cue text tokenizer (spec §6.4 defers to HTML's "consume a character reference").
//
// Sources: `character-entities` (all names that require a trailing semicolon) and
// `character-entities-legacy` (the subset that is also recognized without one). Together they
// are the WHATWG table (https://html.spec.whatwg.org/entities.json): 2,231 entries.
// Usage: node scripts/gen-entities.mjs
import { writeFileSync } from 'node:fs';
import { characterEntities } from 'character-entities';
import { characterEntitiesLegacy } from 'character-entities-legacy';

const entries = [];
for (const name of Object.keys(characterEntities).sort()) {
  entries.push([`${name};`, characterEntities[name]]);
}
for (const name of [...characterEntitiesLegacy].sort()) {
  if (!(name in characterEntities)) throw new Error(`Legacy name without full entry: ${name}`);
  entries.push([name, characterEntities[name]]);
}
if (entries.length !== 2231) throw new Error(`Expected 2231 entries, got ${entries.length}`);

const escape = (s) =>
  [...s]
    .map((ch) => {
      const cp = ch.codePointAt(0);
      if (ch === '\\' || ch === "'") return `\\${ch}`;
      if (cp >= 0x20 && cp < 0x7f) return ch;
      return cp > 0xffff ? `\\u{${cp.toString(16)}}` : `\\u${cp.toString(16).padStart(4, '0')}`;
    })
    .join('');

const body = entries.map(([n, v]) => `'${n}','${escape(v)}'`).join(',\n');
const out = `// Generated by scripts/gen-entities.mjs. Do not edit.
// HTML named character references (WHATWG table, ${entries.length} entries). Names include the
// trailing semicolon where one is required; legacy names also appear without it.
// prettier-ignore
const pairs: readonly string[] = [
${body},
];

export const NAMED_CHARACTER_REFERENCES: ReadonlyMap<string, string> = (() => {
  const map = new Map<string, string>();
  for (let i = 0; i < pairs.length; i += 2) map.set(pairs[i] as string, pairs[i + 1] as string);
  return map;
})();

/** Length of the longest name, including its semicolon. */
export const MAX_NAMED_REFERENCE_LENGTH = ${Math.max(...entries.map(([n]) => n.length))};
`;
writeFileSync(new URL('../packages/core/src/entities.generated.ts', import.meta.url), out);
console.log(`Wrote ${entries.length} entries`);
