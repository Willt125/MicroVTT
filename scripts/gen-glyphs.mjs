// Generates packages/core/src/quality/netflix-glyphs.generated.ts: the code points of the
// Netflix Glyph List, version 2 (NGL2), as ranges, for the `glyph-list` style rule.
//
// Source: Netflix's "NGL2" spreadsheet (export of its "NGL2 Source" sheet as CSV), columns
// "Unicode Code Point" (e.g. 0x00e9), "Character", "Description". Only the code points are kept.
// The CSV is Netflix's and is not committed.
// Usage: node scripts/gen-glyphs.mjs path/to/ngl2.csv
import { readFileSync, writeFileSync } from 'node:fs';

const path = process.argv[2];
if (!path) throw new Error('Usage: node scripts/gen-glyphs.mjs path/to/ngl2.csv');
const lines = readFileSync(path, 'utf8').split(/\r?\n/);
if (!lines[0]?.startsWith('Unicode Code Point,')) throw new Error('Not the NGL2 CSV export');

const codePoints = new Set();
for (const line of lines.slice(1)) {
  if (line.trim() === '') continue;
  const m = /^0x([0-9a-f]{4,6}),/i.exec(line);
  if (!m) throw new Error(`Unexpected row: ${line.slice(0, 60)}`);
  codePoints.add(parseInt(m[1], 16));
}
const sorted = [...codePoints].sort((a, b) => a - b);
const ranges = [];
for (const cp of sorted) {
  const last = ranges[ranges.length - 1];
  if (last && last[1] === cp - 1) last[1] = cp;
  else ranges.push([cp, cp]);
}

const text = ranges
  .map(([a, b]) => (a === b ? a.toString(36) : `${a.toString(36)}-${b.toString(36)}`))
  .join(',');
const out = `// Generated by scripts/gen-glyphs.mjs. Do not edit.
// The Netflix Glyph List, version 2 (NGL2): ${sorted.length} code points in ${ranges.length} ranges,
// written "start-end" or "single", in base 36.
// prettier-ignore
export const NETFLIX_GLYPH_RANGES =
  '${text}';
`;
writeFileSync(
  new URL('../packages/core/src/quality/netflix-glyphs.generated.ts', import.meta.url),
  out,
);
console.log(`${sorted.length} code points, ${ranges.length} ranges, ${out.length} bytes`);
